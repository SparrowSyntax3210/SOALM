def prediction_engine(
    latitude: float,
    longitude: float,
    elevation: float = 0.0,
    weather_override: dict[str, Any] | None = None,
    feature_override: dict[str, Any] | None = None,
) -> dict[str, Any]:
    start = time.perf_counter()

    validate_coordinates(latitude, longitude)

    if not MODELS:
        raise RuntimeError("No SOALM models are loaded")

    weather_start = time.perf_counter()
    weather_source = "override"
    weather_meta = None
    if weather_override is None:
        weather, weather_source, weather_meta = get_weather(latitude, longitude)
    else:
        weather = weather_override
    weather_seconds = time.perf_counter() - weather_start

    feature_start = time.perf_counter()

    if feature_override is None:
        X, feature_dict = create_features_from_weather_source(
            weather, latitude, longitude, elevation
        )
    else:
        feature_dict = {
            key: safe_float(value) for key, value in feature_override.items()
        }
        feature_dict.setdefault("latitude", latitude)
        feature_dict.setdefault("longitude", longitude)
        feature_dict.setdefault("elevation", elevation)
        X = features_to_dataframe(feature_dict)

    feature_seconds = time.perf_counter() - feature_start

    model_start = time.perf_counter()
    predictions, probabilities, model_results = run_models(X)
    model_seconds = time.perf_counter() - model_start

    if not predictions:
        raise RuntimeError("No model produced a prediction")

    summary = build_risk_summary(predictions, probabilities)
    total_seconds = time.perf_counter() - start

    return {
        "success": True,
        "engine": {
            "name": "SOALM",
            "version": SOALM_VERSION,
            "models_loaded": len(MODELS),
            "models_expected": MODEL_COUNT,
            "features": len(FEATURES),
            "classification_probability": True,
        },
        "location": {
            "latitude": latitude,
            "longitude": longitude,
            "elevation": elevation,
        },
        "weather": {
            "source": weather_source,
            "offline": weather_source == "offline-cache",
            "cache": weather_meta,
        },
        "feature_count": len(FEATURES),
        "feature_names": FEATURES,
        "feature_vector": feature_dict,
        "features": feature_dict,
        "prediction": summary,
        "probabilities": probabilities,
        "model_results": model_results,
        "raw_predictions": predictions,
        "performance": {
            "weather_seconds": round(weather_seconds, 3),
            "feature_seconds": round(feature_seconds, 3),
            "model_seconds": round(model_seconds, 3),
            "total_seconds": round(total_seconds, 3),
        },
        "timestamp": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
    }


