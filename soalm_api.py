def run_models_batch(
    X: pd.DataFrame,
) -> list[tuple[dict[str, Any], dict[str, Any], dict[str, Any]]]:
    """
    Run ALL 29 SOALM models concurrently over an arbitrary number of rows.

    Input:
        X = N x 40 feature dataframe

    Output:
        one (predictions, probabilities, model_results) tuple per row.

    This is the main performance optimization:
      OLD: 29 model calls x N spatial points
      NEW: 29 concurrent model calls, each operating on all N rows
    """
    if X is None or len(X) == 0:
        return []

    with MODEL_LOCK:
        loaded_models = dict(MODELS)
        metadata = dict(MODEL_METADATA)

    if not loaded_models:
        raise RuntimeError("No SOALM models are loaded")

    row_count = len(X)
    per_row_predictions = [{} for _ in range(row_count)]
    per_row_probabilities = [{} for _ in range(row_count)]
    per_row_results = [{} for _ in range(row_count)]

    jobs = []
    for target in REGRESSION_TARGETS:
        model = loaded_models.get(target)
        if model is not None:
            jobs.append((target, model, "regression"))

    for target in CLASSIFICATION_TARGETS:
        model = loaded_models.get(target)
        if model is not None:
            jobs.append((target, model, "classification"))

    if not jobs:
        return [({}, {}, {}) for _ in range(row_count)]

    workers = max(1, min(MODEL_WORKERS, len(jobs)))
    start = time.perf_counter()

    with ThreadPoolExecutor(
        max_workers=workers,
        thread_name_prefix="soalm-model",
    ) as executor:
        futures = {
            executor.submit(_run_single_model_batch, target, model, X, kind): (
                target,
                kind,
                model,
            )
            for target, model, kind in jobs
        }

        for future in as_completed(futures):
            target, kind, model = futures[future]
            try:
                target, kind, raw_values, probability_matrix, _ = future.result()
            except Exception as exc:
                log(f"Model failed for {target}: {exc}")
                continue

            model_meta = metadata.get(target, {})
            model_name = model_meta.get("type", type(model).__name__)
            classes = get_model_classes(target, model)

            if kind == "regression":
                for row_index, raw_value in enumerate(raw_values):
                    value = max(0.0, safe_float(raw_value))
                    per_row_predictions[row_index][target] = value
                    per_row_results[row_index][target] = {
                        "target": target,
                        "type": "regression",
                        "prediction": value,
                        "model_loaded": True,
                        "model_type": model_name,
                        "model_classes": classes,
                    }
            else:
                for row_index, raw_value in enumerate(raw_values):
                    predicted_class = classification_result(target, raw_value)

                    probability_row = None
                    if probability_matrix is not None and row_index < len(
                        probability_matrix
                    ):
                        probability_row = probability_matrix[row_index]

                    probability = _classification_probability_for_row(
                        target,
                        model,
                        raw_value,
                        probability_row,
                    )

                    per_row_predictions[row_index][target] = predicted_class
                    per_row_probabilities[row_index][target] = probability
                    per_row_results[row_index][target] = {
                        "target": target,
                        "type": "classification",
                        "prediction": json_safe(predicted_class),
                        "predicted_class": json_safe(predicted_class),
                        **probability,
                        "model_type": model_name,
                    }

    elapsed = time.perf_counter() - start
    log(
        f"Parallel inference: {len(jobs)} models x {row_count} rows "
        f"in {elapsed:.3f}s using {workers} workers"
    )

    return list(
        zip(
            per_row_predictions,
            per_row_probabilities,
            per_row_results,
        )
    )


def run_models(
    X: pd.DataFrame,
) -> tuple[dict[str, Any], dict[str, Any], dict[str, Any]]:
    """Backward-compatible single-row wrapper around run_models_batch()."""
    batches = run_models_batch(X)
    if not batches:
        return {}, {}, {}
    return batches[0]


