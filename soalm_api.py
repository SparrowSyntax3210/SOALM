def _load_one_model(target: str):
    """Load one serialized model. Safe to execute concurrently."""
    path = MODEL_DIR / f"{target}.joblib"

    if not path.exists():
        return target, None, None, f"missing model -> {target}"

    try:
        bundle = joblib.load(path)

        if isinstance(bundle, dict):
            model = bundle.get("model")
            metadata = {
                "type": bundle.get("type", "unknown"),
                "features": bundle.get("features", FEATURES),
                "classes": bundle.get("classes"),
                "mapping": bundle.get("mapping"),
                "training_rows": bundle.get("training_rows"),
            }
        else:
            model = bundle
            metadata = {
                "type": "unknown",
                "features": FEATURES,
                "classes": None,
                "mapping": None,
                "training_rows": None,
            }

        if model is None or not hasattr(model, "predict"):
            raise RuntimeError("Loaded file does not contain a usable model")

        # Prevent nested parallelism. We parallelize target models ourselves.
        if USE_SINGLE_THREAD_PER_MODEL and hasattr(model, "n_jobs"):
            try:
                model.n_jobs = 1
            except Exception:
                pass

        return target, model, metadata, None

    except Exception as exc:
        return target, None, None, str(exc)


def load_all_models() -> None:
    global MODELS_READY

    log("=" * 72)
    log("SOALM V2 MODEL INITIALIZATION — PARALLEL LOAD")
    log(f"Model directory: {MODEL_DIR}")
    log(f"Model load workers: {MODEL_LOAD_WORKERS}")

    if not MODEL_DIR.exists():
        MODELS_READY = False
        log("WARNING: model directory does not exist")
        log("=" * 72)
        return

    start = time.perf_counter()
    loaded = 0

    with MODEL_LOCK:
        MODELS.clear()
        MODEL_METADATA.clear()

    # Load independent .joblib files concurrently.
    with ThreadPoolExecutor(
        max_workers=MODEL_LOAD_WORKERS,
        thread_name_prefix="soalm-load",
    ) as executor:
        futures = {
            executor.submit(_load_one_model, target): target for target in ALL_TARGETS
        }

        for future in as_completed(futures):
            target = futures[future]
            try:
                target, model, metadata, error = future.result()
            except Exception as exc:
                log(f"FAILED {target}: {exc}")
                continue

            if model is None:
                log(f"WARNING: {error}")
                continue

            with MODEL_LOCK:
                MODELS[target] = model
                MODEL_METADATA[target] = metadata

            loaded += 1
            log(f"OK {target}")

    gc.collect()

    MODELS_READY = loaded == MODEL_COUNT

    log(f"Models loaded: {loaded}/{MODEL_COUNT}")
    log(f"Parallel model workers: {MODEL_WORKERS}")
    log(f"Startup loading time: {time.perf_counter() - start:.2f}s")
    log(f"Production ready: {MODELS_READY}")
    log("=" * 72)


# Load exactly once when the module is imported.
load_all_models()


