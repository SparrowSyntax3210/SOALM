WHAT_IF_ALLOWED = {
    "temperature_2m",
    "relative_humidity_2m",
    "precipitation",
    "rain",
    "showers",
    "cloud_cover",
    "surface_pressure",
    "wind_speed_10m",
    "rain_last_1h",
    "rain_last_3h",
    "rain_last_6h",
    "rain_last_12h",
    "rain_last_24h",
    "rain_last_48h",
    "rain_last_72h",
}


def apply_what_if(
    features: dict[str, Any],
    changes: dict[str, Any],
) -> dict[str, float]:
    modified = {feature: safe_float(features.get(feature, 0.0)) for feature in FEATURES}

    unknown = sorted(set(changes) - WHAT_IF_ALLOWED)
    if unknown:
        raise ValueError("Unsupported what-if fields: " + ", ".join(unknown))

    for key, raw_value in changes.items():
        value = safe_float(raw_value, modified.get(key, 0.0))

        if key in {
            "rain",
            "precipitation",
            "showers",
            "rain_last_1h",
            "rain_last_3h",
            "rain_last_6h",
            "rain_last_12h",
            "rain_last_24h",
            "rain_last_48h",
            "rain_last_72h",
        }:
            value = max(0.0, value)

        if key == "relative_humidity_2m":
            value = max(0.0, min(100.0, value))

        modified[key] = value

    # Preserve historical values while recalculating derived deltas.
    if "temperature_2m" in changes:
        old = safe_float(features.get("temperature_2m"))
        d3 = safe_float(features.get("temperature_change_3h"))
        d6 = safe_float(features.get("temperature_change_6h"))
        modified["temperature_change_3h"] = modified["temperature_2m"] - (old - d3)
        modified["temperature_change_6h"] = modified["temperature_2m"] - (old - d6)

    if "relative_humidity_2m" in changes:
        old = safe_float(features.get("relative_humidity_2m"))
        d3 = safe_float(features.get("humidity_change_3h"))
        d6 = safe_float(features.get("humidity_change_6h"))
        modified["humidity_change_3h"] = modified["relative_humidity_2m"] - (old - d3)
        modified["humidity_change_6h"] = modified["relative_humidity_2m"] - (old - d6)

    if "wind_speed_10m" in changes:
        old = safe_float(features.get("wind_speed_10m"))
        d3 = safe_float(features.get("wind_change_3h"))
        d6 = safe_float(features.get("wind_change_6h"))
        modified["wind_change_3h"] = modified["wind_speed_10m"] - (old - d3)
        modified["wind_change_6h"] = modified["wind_speed_10m"] - (old - d6)

    if "surface_pressure" in changes:
        old = safe_float(features.get("surface_pressure"))
        d1 = safe_float(features.get("pressure_change_1h"))
        d3 = safe_float(features.get("pressure_change_3h"))
        d6 = safe_float(features.get("pressure_change_6h"))
        modified["pressure_change_1h"] = modified["surface_pressure"] - (old - d1)
        modified["pressure_change_3h"] = modified["surface_pressure"] - (old - d3)
        modified["pressure_change_6h"] = modified["surface_pressure"] - (old - d6)

    # "rain" represents the current hourly rainfall scenario. Rebuild rolling
    # rain features consistently instead of using max(old, new), which could
    # create an impossible history.
    if "rain" in changes:
        new_rain = max(0.0, safe_float(changes["rain"]))
        old_current = max(0.0, safe_float(features.get("rain")))

        for hours, key in (
            (1, "rain_last_1h"),
            (3, "rain_last_3h"),
            (6, "rain_last_6h"),
            (12, "rain_last_12h"),
            (24, "rain_last_24h"),
            (48, "rain_last_48h"),
            (72, "rain_last_72h"),
        ):
            old_sum = safe_float(features.get(key))
            modified[key] = max(
                0.0,
                old_sum - old_current + new_rain,
            )

        modified["rain"] = new_rain
        modified["precipitation"] = new_rain

    return modified


