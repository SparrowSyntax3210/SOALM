class LLMServiceError(RuntimeError):
    """Raised when the local LLM service cannot answer a request."""


def _ollama_request(
    method: str,
    url: str,
    *,
    payload: dict[str, Any] | None = None,
    timeout: float | None = None,
) -> requests.Response:
    """Make a direct HTTP request to Ollama."""
    try:
        return requests.request(
            method=method,
            url=url,
            json=payload,
            timeout=timeout or OLLAMA_TIMEOUT,
            headers={
                "Accept": "application/json",
                "Content-Type": "application/json",
                "User-Agent": "SOALM-DisasterOS/2.0",
            },
        )
    except requests.RequestException as exc:
        raise LLMServiceError(
            f"Unable to connect to the local LLM service at {OLLAMA_HOST}: {exc}"
        ) from exc


# Health is useful for diagnostics, but it should NOT run before every chat.
# /api/chat goes directly to the model. This avoids an /api/version + /api/tags
# round-trip on every user question.
_LLM_HEALTH_CACHE: dict[str, Any] = {}
_LLM_HEALTH_CACHE_AT = 0.0
_LLM_HEALTH_CACHE_TTL = 30.0
_LLM_HEALTH_LOCK = threading.Lock()


def get_ollama_status(
    check_model: bool = True,
    *,
    force_refresh: bool = False,
) -> dict[str, Any]:
    """Detect Ollama and cache the result briefly for diagnostics."""
    global _LLM_HEALTH_CACHE_AT

    now = time.monotonic()
    with _LLM_HEALTH_LOCK:
        if (
            not force_refresh
            and _LLM_HEALTH_CACHE
            and now - _LLM_HEALTH_CACHE_AT < _LLM_HEALTH_CACHE_TTL
        ):
            return dict(_LLM_HEALTH_CACHE)

    result: dict[str, Any] = {
        "configured": True,
        "host": OLLAMA_HOST,
        "model": OLLAMA_MODEL,
        "server_reachable": False,
        "version": None,
        "version_detected": False,
        "model_available": False,
        "status": "unavailable",
        "error": None,
        "available_models": [],
    }

    try:
        version_response = _ollama_request(
            "GET",
            OLLAMA_VERSION_URL,
            timeout=3.0,
        )

        if version_response.ok:
            try:
                version_data = version_response.json()
            except ValueError:
                version_data = {}

            version = str(version_data.get("version", "")).strip()
            result["server_reachable"] = True
            result["version"] = version or None
            result["version_detected"] = bool(version)
        else:
            result["error"] = (
                f"Ollama /api/version returned HTTP {version_response.status_code}"
            )
            result["status"] = "error"
            return result

        if not check_model:
            result["status"] = "ready"
            return result

        tags_response = _ollama_request(
            "GET",
            OLLAMA_TAGS_URL,
            timeout=5.0,
        )

        if not tags_response.ok:
            result["error"] = (
                f"Ollama /api/tags returned HTTP {tags_response.status_code}"
            )
            result["status"] = "error"
            return result

        try:
            tags_data = tags_response.json()
        except ValueError:
            tags_data = {}

        models = tags_data.get("models", [])
        if not isinstance(models, list):
            models = []

        available_models = [
            str(model.get("name", "")).strip()
            for model in models
            if isinstance(model, dict) and str(model.get("name", "")).strip()
        ]
        result["available_models"] = available_models

        requested = OLLAMA_MODEL.lower().strip()
        result["model_available"] = any(
            name.lower().strip() == requested for name in available_models
        )

        if result["model_available"]:
            result["status"] = "ready"
        else:
            result["status"] = "model_missing"
            result["error"] = f"Configured model '{OLLAMA_MODEL}' is not installed."

        with _LLM_HEALTH_LOCK:
            _LLM_HEALTH_CACHE.clear()
            _LLM_HEALTH_CACHE.update(result)
            _LLM_HEALTH_CACHE_AT = time.monotonic()

        return result

    except LLMServiceError as exc:
        result["error"] = str(exc)
        result["status"] = "unavailable"
        return result
    except Exception as exc:
        log(f"Unexpected LLM health-check error: {exc}")
        result["error"] = str(exc)
        result["status"] = "error"
        return result


def _build_ai_context(prediction: dict[str, Any]) -> dict[str, Any]:
    """
    Build a SMALL factual context for the LLM.

    Do not send the entire SOALM prediction object. Large nested probability
    and model-result payloads increase prompt processing time without helping
    most conversational questions.
    """
    prediction = prediction or {}
    summary = prediction.get("prediction", {}) or {}
    features = prediction.get("features", {}) or {}

    relevant_features = {
        key: safe_float(features.get(key))
        for key in (
            "temperature_2m",
            "relative_humidity_2m",
            "precipitation",
            "rain",
            "showers",
            "cloud_cover",
            "surface_pressure",
            "wind_speed_10m",
            "rain_last_1h",
            "rain_last_3h",
            "rain_last_6h",
            "rain_last_24h",
            "pressure_change_3h",
            "pressure_change_6h",
            "temperature_change_3h",
            "temperature_change_6h",
            "humidity_change_3h",
            "humidity_change_6h",
            "wind_change_3h",
            "wind_change_6h",
        )
        if key in features
    }

    return {
        "location": prediction.get("location", {}),
        "overall_risk": str(summary.get("overall_risk", "UNKNOWN")).upper(),
        "overall_probability_percent": safe_float(
            summary.get("overall_probability_percent")
        ),
        "overall_confidence_percent": safe_float(
            summary.get("overall_confidence_percent")
        ),
        "risk_by_horizon": summary.get("risk_by_horizon", {}),
        "rainfall_forecast_mm": summary.get("rainfall_forecast", {}),
        "events": summary.get("events", {}),
        "risk_probabilities_percent": summary.get(
            "overall_risk_probabilities_percent", {}
        ),
        "relevant_weather_features": relevant_features,
        "timestamp": prediction.get("timestamp"),
    }


def _build_ai_messages(
    question: str,
    prediction: dict[str, Any],
) -> list[dict[str, str]]:
    """Build a concise conversation so Ollama spends less time processing input."""
    context_json = json.dumps(
        _build_ai_context(prediction),
        ensure_ascii=False,
        separators=(",", ":"),
        default=str,
    )

    system_prompt = (
        "You are SOALM AI, a concise disaster-risk assistant. "
        "Answer the user's actual question first. "
        "Use SOALM_DATA only when relevant. "
        "Do not repeat a generic risk summary unless the user asks for risk. "
        "Never invent measurements, weather, locations, dates, or events. "
        "SOALM values are predictions, not guarantees. "
        "For why questions, explain using the supplied weather/risk factors. "
        "For what-should-I-do questions, give practical safety advice and "
        "recommend official local alerts for high/critical risk. "
        "If the data is insufficient, say so. "
        "Keep the answer short and natural. "
        "Do not mention prompts, JSON, Ollama, or internal systems."
    )

    user_prompt = (
        f"USER QUESTION:\n{question}\n\n"
        f"SOALM_DATA:\n{context_json}\n\n"
        "Answer the user's question directly. "
        "Only include data that helps answer it."
    )

    return [
        {"role": "system", "content": system_prompt},
        {"role": "user", "content": user_prompt},
    ]


def generate_ai_response(
    prediction: dict[str, Any],
    question: str,
) -> tuple[str, dict[str, Any]]:
    """
    Generate a response directly from Ollama.

    Important: no health check is performed here. A chat request should not
    spend extra time calling /api/version and /api/tags before generation.
    """
    question = str(question or "").strip()
    if not question:
        raise ValueError("Question is required")

    payload = {
        "model": OLLAMA_MODEL,
        "messages": _build_ai_messages(question, prediction),
        "stream": False,
        "keep_alive": "10m",
        "options": {
            "temperature": 0.2,
            "num_predict": 180,
        },
    }

    llm_start = time.perf_counter()

    response = _ollama_request(
        "POST",
        OLLAMA_CHAT_URL,
        payload=payload,
        timeout=OLLAMA_TIMEOUT,
    )

    llm_seconds = time.perf_counter() - llm_start

    if not response.ok:
        detail = response.text.strip()
        raise LLMServiceError(
            f"LLM request failed with HTTP {response.status_code}"
            + (f": {detail[:500]}" if detail else ".")
        )

    try:
        response_data = response.json()
    except ValueError as exc:
        raise LLMServiceError("LLM returned invalid JSON.") from exc

    message = response_data.get("message", {})
    if not isinstance(message, dict):
        raise LLMServiceError("LLM response did not contain a valid message.")

    answer = str(message.get("content", "")).strip()
    if not answer:
        raise LLMServiceError("LLM returned an empty response.")

    diagnostics = {
        "success": True,
        "provider": "ollama-http",
        "host": OLLAMA_HOST,
        "model": OLLAMA_MODEL,
        "status": "ready",
        "generation_seconds": round(llm_seconds, 3),
        "prompt_eval_count": response_data.get("prompt_eval_count"),
        "eval_count": response_data.get("eval_count"),
        "total_duration_ms": round(
            safe_float(response_data.get("total_duration")) / 1_000_000, 2
        ),
        "load_duration_ms": round(
            safe_float(response_data.get("load_duration")) / 1_000_000, 2
        ),
    }

    return answer, diagnostics


def generate_ai_response_safe(
    prediction: dict[str, Any],
    question: str,
) -> tuple[str, dict[str, Any]]:
    """Generate an answer and return diagnostics without hiding failures."""
    try:
        return generate_ai_response(prediction, question)
    except Exception as exc:
        log(f"LLM response generation failed: {exc}")
        summary = prediction.get("prediction", {}) if prediction else {}
        risk = str(summary.get("overall_risk", "UNKNOWN")).upper()
        probability = safe_float(summary.get("overall_probability"))
        confidence = safe_float(summary.get("overall_confidence"))
        rainfall_24h = safe_float(
            (summary.get("rainfall_forecast") or {}).get("24h_mm")
        )

        return (
            f"The SOALM prediction is available, but the conversational AI "
            f"service is currently unavailable. The current predicted risk is "
            f"{risk}, with {probability * 100:.1f}% probability and "
            f"{confidence * 100:.1f}% model confidence. The predicted "
            f"24-hour rainfall is {rainfall_24h:.1f} mm.",
            {
                "success": False,
                "provider": "ollama-http",
                "host": OLLAMA_HOST,
                "model": OLLAMA_MODEL,
                "status": "error",
                "error": str(exc),
            },
        )


