def require_json() -> dict[str, Any]:
    data = request.get_json(silent=True)
    if data is None:
        raise ValueError("Request body must be valid JSON")
    if not isinstance(data, dict):
        raise ValueError("Request body must be a JSON object")
    return data


def validate_coordinates(latitude: float, longitude: float) -> None:
    if not math.isfinite(latitude):
        raise ValueError("latitude is required")

    if not math.isfinite(longitude):
        raise ValueError("longitude is required")

    if not -90.0 <= latitude <= 90.0:
        raise ValueError("latitude must be between -90 and 90")

    if not -180.0 <= longitude <= 180.0:
        raise ValueError("longitude must be between -180 and 180")


def parse_location(data: dict[str, Any]) -> tuple[float, float, float]:
    latitude = safe_float(data.get("latitude"), math.nan)
    longitude = safe_float(data.get("longitude"), math.nan)
    elevation = safe_float(data.get("elevation", 0.0), 0.0)

    validate_coordinates(latitude, longitude)

    if not math.isfinite(elevation):
        elevation = 0.0

    return latitude, longitude, elevation


def parse_changes(data: dict[str, Any]) -> dict[str, Any]:
    changes = data.get("changes", {})
    if changes is None:
        return {}
    if not isinstance(changes, dict):
        raise ValueError("changes must be an object")
    return changes


def spatial_config(data: dict[str, Any]) -> tuple[float, int, int]:
    default_radius = safe_float(
        getattr(spatial_engine, "DEFAULT_RADIUS_KM", 5.0),
        5.0,
    )
    default_rows = safe_int(
        getattr(spatial_engine, "DEFAULT_ROWS", 5),
        5,
    )
    default_cols = safe_int(
        getattr(spatial_engine, "DEFAULT_COLS", 5),
        5,
    )
    engine_min = safe_int(
        getattr(spatial_engine, "MIN_GRID_SIZE", MIN_GRID),
        MIN_GRID,
    )
    engine_max = safe_int(
        getattr(spatial_engine, "MAX_GRID_SIZE", MAX_GRID),
        MAX_GRID,
    )
    engine_max_radius = safe_float(
        getattr(spatial_engine, "MAX_RADIUS_KM", MAX_RADIUS_KM),
        MAX_RADIUS_KM,
    )

    radius = safe_float(data.get("radius_km", default_radius), math.nan)
    rows = safe_int(data.get("rows", default_rows), default_rows)
    cols = safe_int(data.get("cols", default_cols), default_cols)

    if not math.isfinite(radius) or radius <= 0:
        raise ValueError("radius_km must be greater than 0")

    if radius > min(MAX_RADIUS_KM, engine_max_radius):
        raise ValueError(
            f"radius_km cannot exceed {min(MAX_RADIUS_KM, engine_max_radius)} km"
        )

    if not engine_min <= rows <= min(MAX_GRID, engine_max):
        raise ValueError(
            f"rows must be between {engine_min} and {min(MAX_GRID, engine_max)}"
        )

    if not engine_min <= cols <= min(MAX_GRID, engine_max):
        raise ValueError(
            f"cols must be between {engine_min} and {min(MAX_GRID, engine_max)}"
        )

    return radius, rows, cols


