def _weather_dataframe(weather: dict[str, Any]) -> pd.DataFrame:
    hourly = weather.get("hourly")
    if not isinstance(hourly, dict) or not hourly:
        raise RuntimeError("Weather response contains no hourly data")

    df = pd.DataFrame(hourly)

    if df.empty or "time" not in df.columns:
        raise RuntimeError("Weather response has no usable time series")

    df["time"] = pd.to_datetime(df["time"], utc=True, errors="coerce")
    df = df.dropna(subset=["time"]).sort_values("time").reset_index(drop=True)

    if df.empty:
        raise RuntimeError("Weather response contains no valid timestamps")

    for column in HOURLY_VARIABLES:
        if column not in df.columns:
            df[column] = 0.0
        df[column] = pd.to_numeric(df[column], errors="coerce").fillna(0.0)

    return df


def _current_row_index(df: pd.DataFrame) -> int:
    """
    Select the hour nearest to now rather than blindly using the last forecast
    hour. This prevents the 3-day forecast tail from becoming the model input.
    """
    now = pd.Timestamp.now(tz="UTC")

    deltas = (df["time"] - now).abs()
    return int(deltas.idxmin())


def create_features(
    weather: dict[str, Any],
    latitude: float,
    longitude: float,
    elevation: float = 0.0,
) -> tuple[pd.DataFrame, dict[str, float]]:
    df = _weather_dataframe(weather)
    current_idx = _current_row_index(df)

    def value(column: str, offset: int = 0) -> float:
        idx = current_idx + offset
        if idx < 0 or idx >= len(df):
            return 0.0
        return safe_float(df.at[idx, column], 0.0)

    rain_series = pd.to_numeric(df["rain"], errors="coerce").fillna(0.0)

    def rain_sum(hours: int) -> float:
        start = max(0, current_idx - hours + 1)
        return max(0.0, safe_float(rain_series.iloc[start : current_idx + 1].sum()))

    temperature = value("temperature_2m")
    humidity = value("relative_humidity_2m")
    pressure = value("surface_pressure")
    wind = value("wind_speed_10m")

    timestamp = df.at[current_idx, "time"]

    hour = int(timestamp.hour)
    day_of_week = int(timestamp.dayofweek)
    month = int(timestamp.month)
    day_of_year = int(timestamp.dayofyear)

    pressure_1h = value("surface_pressure", -1)
    pressure_3h = value("surface_pressure", -3)
    pressure_6h = value("surface_pressure", -6)

    temperature_3h = value("temperature_2m", -3)
    temperature_6h = value("temperature_2m", -6)

    humidity_3h = value("relative_humidity_2m", -3)
    humidity_6h = value("relative_humidity_2m", -6)

    wind_3h = value("wind_speed_10m", -3)
    wind_6h = value("wind_speed_10m", -6)

    features = {
        "temperature_2m": temperature,
        "relative_humidity_2m": humidity,
        "dew_point_2m": value("dew_point_2m"),
        "precipitation": max(0.0, value("precipitation")),
        "rain": max(0.0, value("rain")),
        "showers": max(0.0, value("showers")),
        "cloud_cover": value("cloud_cover"),
        "surface_pressure": pressure,
        "wind_speed_10m": max(0.0, wind),
        "wind_direction_10m": value("wind_direction_10m"),
        "shortwave_radiation": max(0.0, value("shortwave_radiation")),
        "rain_last_1h": rain_sum(1),
        "rain_last_3h": rain_sum(3),
        "rain_last_6h": rain_sum(6),
        "rain_last_12h": rain_sum(12),
        "rain_last_24h": rain_sum(24),
        "rain_last_48h": rain_sum(48),
        "rain_last_72h": rain_sum(72),
        "pressure_change_1h": pressure - pressure_1h,
        "pressure_change_3h": pressure - pressure_3h,
        "pressure_change_6h": pressure - pressure_6h,
        "temperature_change_3h": temperature - temperature_3h,
        "temperature_change_6h": temperature - temperature_6h,
        "humidity_change_3h": humidity - humidity_3h,
        "humidity_change_6h": humidity - humidity_6h,
        "wind_change_3h": wind - wind_3h,
        "wind_change_6h": wind - wind_6h,
        "latitude": latitude,
        "longitude": longitude,
        "elevation": elevation,
        "hour": hour,
        "day_of_week": day_of_week,
        "month": month,
        "day_of_year": day_of_year,
        "hour_sin": math.sin(2 * math.pi * hour / 24),
        "hour_cos": math.cos(2 * math.pi * hour / 24),
        "month_sin": math.sin(2 * math.pi * month / 12),
        "month_cos": math.cos(2 * math.pi * month / 12),
        "day_of_year_sin": math.sin(2 * math.pi * day_of_year / 365),
        "day_of_year_cos": math.cos(2 * math.pi * day_of_year / 365),
    }

    return features_to_dataframe(features), features


def features_to_dataframe(features: dict[str, Any]) -> pd.DataFrame:
    row = {feature: safe_float(features.get(feature, 0.0), 0.0) for feature in FEATURES}

    X = pd.DataFrame([row], columns=FEATURES)
    X = X.replace([np.inf, -np.inf], 0.0).fillna(0.0).astype(np.float32)

    return X


