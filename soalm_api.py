def fetch_weather_offline(
    latitude: float,
    longitude: float,
) -> tuple[dict[str, Any], dict[str, float], dict[str, Any]]:
    """
    Get weather from the local weather.json cache.

    The requested location does not need to exactly match
    a cached grid. The geographically nearest grid is used.

    Returns:
        weather_marker
        feature_dict
        metadata
    """

    cache = load_weather_cache()

    age = _cache_age_hours(cache)

    # --------------------------------------------------------
    # FIND NEAREST GRID
    # --------------------------------------------------------

    grid_id, grid, distance_km = _nearest_cached_grid(
        latitude,
        longitude,
        cache,
    )

    # --------------------------------------------------------
    # CONVERT CACHED WEATHER -> SOALM FEATURES
    # --------------------------------------------------------

    features = cached_grid_to_features(
        grid,
        latitude,
        longitude,
        0.0,
    )

    # --------------------------------------------------------
    # METADATA
    # --------------------------------------------------------

    metadata = {
        "source": "offline-cache",
        "offline": True,
        "grid_id": grid_id,
        "requested_latitude": latitude,
        "requested_longitude": longitude,
        "grid_latitude": grid.get("latitude"),
        "grid_longitude": grid.get("longitude"),
        "distance_to_grid_km": round(
            distance_km,
            3,
        ),
        "cache_age_hours": (round(age, 3) if age is not None else None),
        "cache_file": str(WEATHER_CACHE_FILE),
    }

    # --------------------------------------------------------
    # THIS IS THE IMPORTANT PART
    # --------------------------------------------------------
    #
    # create_features_from_weather_source()
    # expects weather["offline_grid"]
    #
    # Previously this field was missing.
    #

    weather_marker = {
        "offline_cache": True,
        # ACTUAL nearest cached grid
        "offline_grid": grid,
        # Useful debugging information
        "metadata": metadata,
    }

    log(
        f"Offline weather selected nearest grid "
        f"{grid_id} | "
        f"user=({latitude:.4f}, {longitude:.4f}) | "
        f"grid=({safe_float(grid.get('latitude')):.4f}, "
        f"{safe_float(grid.get('longitude')):.4f}) | "
        f"distance={distance_km:.2f} km"
    )

    return (
        weather_marker,
        features,
        metadata,
    )


def get_weather(
    latitude: float,
    longitude: float,
) -> tuple[dict[str, Any], str, dict[str, Any] | None]:

    try:
        weather = fetch_weather(latitude, longitude)

        return (
            weather,
            "open-meteo",
            {
                "source": "open-meteo",
                "offline": False,
            },
        )

    except Exception as online_error:

        log(f"Open-Meteo unavailable: {online_error}")

        weather, _, meta = fetch_weather_offline(
            latitude,
            longitude,
        )

        return (
            weather,
            "offline-cache",
            meta,
        )


def get_weather_batch(
    points: list[dict[str, Any]],
) -> tuple[
    list[dict[str, Any]],
    str,
    list[dict[str, Any] | None],
]:

    if not points:
        return [], "none", []

    try:
        weather_list = fetch_weather_batch(points)

        metadata = [
            {
                "source": "open-meteo",
                "offline": False,
            }
            for _ in points
        ]

        return (
            weather_list,
            "open-meteo",
            metadata,
        )

    except Exception as online_error:

        log(f"Open-Meteo batch unavailable: " f"{online_error}")

        weather_list = []
        metadata_list = []

        for point in points:

            weather, _, meta = fetch_weather_offline(
                float(point["latitude"]),
                float(point["longitude"]),
            )

            weather_list.append(weather)
            metadata_list.append(meta)

        return (
            weather_list,
            "offline-cache",
            metadata_list,
        )


def create_features_from_weather_source(
    weather: dict[str, Any],
    latitude: float,
    longitude: float,
    elevation: float,
) -> tuple[pd.DataFrame, dict[str, float]]:

    if weather.get("offline_cache"):

        grid = weather.get("offline_grid")

        if not isinstance(grid, dict):
            raise RuntimeError("Offline weather response has no cached grid")

        features = cached_grid_to_features(
            grid,
            latitude,
            longitude,
            elevation,
        )

        return (
            features_to_dataframe(features),
            features,
        )

    return create_features(
        weather,
        latitude,
        longitude,
        elevation,
    )


