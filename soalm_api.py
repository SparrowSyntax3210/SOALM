def _build_latitude_axis(
    points: list[dict[str, Any]],
    rows: int,
    cols: int,
) -> list[float]:
    return [_point_latitude(points[row * cols]) for row in range(rows)]


def _build_longitude_axis(
    points: list[dict[str, Any]],
    cols: int,
) -> list[float]:
    return [_point_longitude(points[col]) for col in range(cols)]


def validate_spatial_zones(
    zones: Any,
    expected_count: int,
) -> None:
    if not isinstance(zones, list):
        raise RuntimeError("Spatial engine did not return zones")

    if len(zones) != expected_count:
        raise RuntimeError(
            f"Spatial zone mismatch: expected {expected_count}, received {len(zones)}"
        )

    for index, zone in enumerate(zones):
        if not isinstance(zone, dict):
            raise RuntimeError(f"Invalid zone at index {index}")

        coordinates = zone.get("coordinates")
        if not isinstance(coordinates, list) or len(coordinates) < 4:
            raise RuntimeError(f"Zone {index} has invalid polygon coordinates")


def spatial_prediction_core(data: dict[str, Any]) -> dict[str, Any]:
    """
    Complete SOALM spatial prediction pipeline.

    Flow:

        request
          ↓
        generate_grid()
          ↓
        Open-Meteo batch weather
          ↓
        SOALM prediction for every point
          ↓
        spatial_engine.build_zones()
          ↓
        merge prediction + polygon geometry
          ↓
        return zones to frontend
    """

    start = time.perf_counter()

    # ============================================================
    # 1. REQUEST
    # ============================================================

    latitude, longitude, elevation = parse_location(data)
    radius_km, rows, cols = spatial_config(data)
    changes = parse_changes(data)

    expected = rows * cols

    log(
        f"Spatial request: center=({latitude}, {longitude}), "
        f"radius={radius_km} km, grid={rows}x{cols}"
    )

    # ============================================================
    # 2. GENERATE GRID POINTS
    # ============================================================

    points = spatial_engine.generate_grid(
        latitude=latitude,
        longitude=longitude,
        radius_km=radius_km,
        rows=rows,
        cols=cols,
    )

    if not isinstance(points, list):
        raise RuntimeError("spatial_engine.generate_grid() returned an invalid grid")

    if len(points) != expected:
        raise RuntimeError(
            f"Grid mismatch: expected {expected} points, " f"received {len(points)}"
        )

    # Validate every generated point.

    for index, point in enumerate(points):

        if not isinstance(point, dict):
            raise RuntimeError(f"Invalid grid point at index {index}")

        point_lat = _point_latitude(point)
        point_lon = _point_longitude(point)

        validate_coordinates(
            point_lat,
            point_lon,
        )

    log(f"Generated {len(points)} spatial points")

    # ============================================================
    # 3. FETCH WEATHER FOR ALL POINTS
    # ============================================================

    weather_start = time.perf_counter()

    weather_list, weather_source, weather_meta_list = get_weather_batch(points)

    weather_seconds = time.perf_counter() - weather_start

    if len(weather_list) != expected:
        raise RuntimeError(
            f"Weather/grid mismatch: expected {expected}, "
            f"received {len(weather_list)}"
        )

    log(f"Weather received for {len(weather_list)} points")

    # ============================================================
    # 4. RUN SOALM PREDICTION FOR EACH POINT
    # ============================================================

    inference_start = time.perf_counter()

    # ------------------------------------------------------------------
    # Build ALL spatial feature rows first.
    # ------------------------------------------------------------------
    feature_rows = []
    feature_dicts = []

    for point, weather in zip(points, weather_list):
        point_lat = _point_latitude(point)
        point_lon = _point_longitude(point)

        _, features = create_features_from_weather_source(
            weather,
            point_lat,
            point_lon,
            elevation,
        )

        if changes:
            features = apply_what_if(features, changes)

        feature_dicts.append(features)
        feature_rows.append(features_to_dataframe(features))

    # One N-row dataframe -> all 29 models concurrently.
    batch_X = pd.concat(feature_rows, ignore_index=True)
    batch_results = run_models_batch(batch_X)

    if len(batch_results) != expected:
        raise RuntimeError(
            f"Prediction mismatch: expected {expected} rows, "
            f"received {len(batch_results)}"
        )

    prediction_zones = []

    for index, (point, features, model_bundle) in enumerate(
        zip(points, feature_dicts, batch_results)
    ):
        predictions, probabilities, model_results = model_bundle
        summary = build_risk_summary(predictions, probabilities)

        latitude_point = _point_latitude(point)
        longitude_point = _point_longitude(point)
        row = safe_int(point.get("row", index), 0)
        col = safe_int(point.get("col", index), 0)
        zone_id = str(
            point.get("zone_id") or point.get("id") or f"Z{row + 1}_{col + 1}"
        )

        prediction_zones.append(
            {
                "zone_id": zone_id,
                "index": index,
                "row": row,
                "col": col,
                "risk": summary["overall_risk"],
                "probability": summary["overall_probability"],
                "probability_percent": summary["overall_probability_percent"],
                "flood_probability": summary["flood_probability"],
                "flood_probability_percent": summary["flood_probability_percent"],
                "confidence": summary["overall_confidence"],
                "confidence_percent": summary["overall_confidence_percent"],
                "risk_by_horizon": summary["risk_by_horizon"],
                "rainfall_forecast": summary["rainfall_forecast"],
                "events": summary["events"],
                "prediction": summary,
                "raw_predictions": predictions,
                "probabilities": probabilities,
                "model_results": model_results,
                "feature_vector": features,
                "location": {
                    "latitude": latitude_point,
                    "longitude": longitude_point,
                    "elevation": elevation,
                },
                "center": {
                    "latitude": latitude_point,
                    "longitude": longitude_point,
                },
            }
        )

    log(f"SOALM batch predictions generated for {len(prediction_zones)} points")

    # ============================================================
    # 5. BUILD POLYGON GEOMETRY USING EXISTING SPATIAL ENGINE
    # ============================================================

    log(f"Building {expected} spatial polygons")

    try:

        geometry_zones = spatial_engine.build_zones(
            points=points,
            rows=rows,
            cols=cols,
        )

    except TypeError:

        # Compatibility fallback for engines whose signature
        # uses positional arguments.

        geometry_zones = spatial_engine.build_zones(
            points,
            rows,
            cols,
        )

    if not isinstance(geometry_zones, list):
        raise RuntimeError("spatial_engine.build_zones() did not return a list")

    if len(geometry_zones) != expected:
        raise RuntimeError(
            f"Geometry mismatch: expected {expected} zones, "
            f"received {len(geometry_zones)}"
        )

    log(f"Spatial engine generated {len(geometry_zones)} polygons")

    # ============================================================
    # 6. MERGE PREDICTION DATA + GEOMETRY
    # ============================================================

    zones = []

    for index in range(expected):

        prediction_zone = prediction_zones[index]
        geometry_zone = geometry_zones[index]

        if not isinstance(geometry_zone, dict):
            raise RuntimeError(f"Invalid geometry zone at index {index}")

        coordinates = geometry_zone.get("coordinates")

        if not isinstance(coordinates, list) or len(coordinates) < 4:
            raise RuntimeError(f"Zone {index} has invalid polygon coordinates")

        # Start with prediction data.

        zone = dict(prediction_zone)

        # Copy geometry information.

        zone["coordinates"] = coordinates
        zone["polygon"] = coordinates

        if "bounds" in geometry_zone:
            zone["bounds"] = geometry_zone["bounds"]

        # Preserve row / column information.

        zone["row"] = safe_int(
            geometry_zone.get(
                "row",
                prediction_zone.get("row", index),
            )
        )

        zone["col"] = safe_int(
            geometry_zone.get(
                "col",
                prediction_zone.get("col", index),
            )
        )

        # Preserve IDs from geometry engine if available.

        if geometry_zone.get("zone_id"):
            zone["zone_id"] = geometry_zone["zone_id"]

        if geometry_zone.get("id"):
            zone["id"] = geometry_zone["id"]

        # Keep center/location from prediction zone.

        if "center" not in zone:
            zone["center"] = {
                "latitude": _point_latitude(points[index]),
                "longitude": _point_longitude(points[index]),
            }

        zones.append(zone)

    # ============================================================
    # 7. VALIDATE FINAL ZONES
    # ============================================================

    validate_spatial_zones(
        zones,
        expected,
    )

    inference_seconds = time.perf_counter() - inference_start

    # ============================================================
    # 8. RISK DISTRIBUTION
    # ============================================================

    risk_distribution = {
        "LOW": 0,
        "MODERATE": 0,
        "HIGH": 0,
        "CRITICAL": 0,
    }

    for zone in zones:

        risk = str(zone.get("risk", "LOW")).upper()

        if risk in risk_distribution:
            risk_distribution[risk] += 1

    # ============================================================
    # 9. HIGHEST RISK ZONE
    # ============================================================

    highest_risk_zone = max(
        zones,
        key=lambda zone: (
            RISK_ORDER.get(
                str(
                    zone.get(
                        "risk",
                        "LOW",
                    )
                ).upper(),
                0,
            ),
            safe_float(
                zone.get(
                    "probability",
                    0.0,
                )
            ),
        ),
        default=None,
    )

    # ============================================================
    # 10. CENTER ZONE
    # ============================================================

    center_zone = min(
        zones,
        key=lambda zone: (
            (_point_latitude(zone["location"]) - latitude) ** 2
            + (_point_longitude(zone["location"]) - longitude) ** 2
        ),
        default=None,
    )

    # ============================================================
    # 11. OVERALL GRID RISK
    # ============================================================

    overall_grid_risk = max(
        (
            str(
                zone.get(
                    "risk",
                    "LOW",
                )
            ).upper()
            for zone in zones
        ),
        key=lambda risk: RISK_ORDER.get(
            risk,
            0,
        ),
        default="LOW",
    )

    # ============================================================
    # 12. PERFORMANCE
    # ============================================================

